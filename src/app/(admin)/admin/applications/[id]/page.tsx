import Link from 'next/link';
import { notFound } from 'next/navigation';
import { requireAdmin } from '@/lib/session';
import { Badge, Card, Flash, PageHeader, Row } from '@/components/ui';
import { Submit } from '@/components/submit';
import { decideApplication } from '@/app/actions/admin';
import { D, DT, R, label } from '@/lib/format';

export const metadata = { title: 'Review application' };
export default async function Review({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ ok?: string; err?: string }> }) {
  const { id } = await params; const q = await searchParams;
  const { supabase } = await requireAdmin();
  const { data: a } = await supabase.from('applications').select('*, profiles(*)').eq('id', id).single();
  if (!a) notFound();
  const p = a.profiles as unknown as Record<string, string & number>;
  const [{ data: docs }, { data: prior }, { data: sc }] = await Promise.all([
    supabase.from('documents').select('kind,status').eq('customer_id', a.customer_id),
    supabase.from('loans').select('ref,status,total_repayable,paid_total').eq('customer_id', a.customer_id).order('created_at', { ascending: false }),
    supabase.from('settings').select('value').eq('key', 'scoring').single(),
  ]);
  const rules = (sc?.value ?? {}) as Record<string, number>;
  const qt = a.quote as Record<string, number>;
  const ratio = p.monthly_income ? (qt.monthly / Number(p.monthly_income)) * 100 : 0;
  const open = ['pending', 'under_review'].includes(a.status);
  const checks = [
    ['Credit score', `${a.credit_score}`, a.credit_score >= (rules.approve_score ?? 620) ? 'ok' : a.credit_score < (rules.decline_score ?? 480) ? 'bad' : 'warn'],
    ['Instalment vs income', `${ratio.toFixed(0)}% (max ${(Number(rules.max_instalment_pct_income ?? 0.4) * 100).toFixed(0)}%)`, ratio <= Number(rules.max_instalment_pct_income ?? 0.4) * 100 ? 'ok' : 'bad'],
    ['Income', R(p.monthly_income), Number(p.monthly_income) >= (rules.min_income ?? 2500) ? 'ok' : 'bad'],
    ['Documents verified', `${new Set((docs ?? []).filter((d) => d.status === 'verified').map((d) => d.kind)).size}/4`, (docs ?? []).filter((d) => d.status === 'verified').length >= 4 ? 'ok' : 'warn'],
  ];
  const tone = { ok: 'bg-brand', warn: 'bg-amber-500', bad: 'bg-red-500' } as const;
  return (
    <>
      <PageHeader title={`Application ${a.ref}`} sub={`${p.full_name} · submitted ${DT(a.created_at)}`} actions={<Badge status={a.status} />} />
      <Flash ok={q.ok} err={q.err} />
      <div className="grid gap-6 lg:grid-cols-[1.2fr_1fr]">
        <div className="space-y-6">
          <Card title="Assessment">
            <div className="grid gap-3 sm:grid-cols-2">{checks.map(([k, v, t]) => (
              <div key={k} className="flex items-center gap-3 rounded-xl bg-slate-50 p-3"><span className={`h-3 w-3 rounded-full ${tone[t as 'ok']}`} /><div><div className="text-xs text-slate-500">{k}</div><div className="font-bold">{v}</div></div></div>))}</div>
            <p className="mt-3 text-xs text-slate-400">Score is generated by the built-in simulated bureau. Replace with a real credit bureau before going live.</p>
          </Card>
          <Card title="Requested loan"><Row k="Amount" v={R(a.amount)} /><Row k="Term" v={`${a.months} months`} /><Row k="Purpose" v={a.purpose ?? '—'} /><Row k="Interest" v={R(qt.interest)} /><Row k="Service fees" v={R(qt.service_fees)} /><Row k="Initiation fee" v={R(qt.initiation_fee)} /><Row k="Total repayable" v={R(qt.total)} /><Row k="Monthly instalment" v={R(qt.monthly)} /></Card>
          <Card title="Previous loans">{prior?.length ? prior.map((l) => <Row key={l.ref} k={l.ref} v={<><Badge status={l.status} /> <span className="ml-2">{R(l.paid_total)} / {R(l.total_repayable)}</span></>} />) : <p className="text-sm text-slate-500">First-time borrower.</p>}</Card>
        </div>
        <div className="space-y-6">
          <Card title="Customer" actions={<Link href={`/admin/customers/${a.customer_id}`} className="text-sm font-semibold text-brand-600">Profile</Link>}>
            <Row k="Name" v={p.full_name} /><Row k="ID number" v={p.id_number} /><Row k="Phone" v={p.phone} /><Row k="Employer" v={p.employer ?? '—'} /><Row k="Bank" v={`${p.bank_name ?? '—'} ${p.account_number ? '••' + String(p.account_number).slice(-4) : ''}`} />
          </Card>
          {open ? (
            <Card title="Decision">
              <form className="space-y-3"><input type="hidden" name="id" value={a.id} />
                <div><label className="label" htmlFor="note">Note (shown to customer if declined)</label><textarea id="note" name="note" rows={3} className="input" placeholder="Reason or comment" /></div>
                <div className="grid grid-cols-2 gap-3">
                  <button formAction={decideApplicationApprove} className="btn-primary">Approve</button>
                  <button formAction={decideApplicationDecline} className="btn-danger">Decline</button>
                </div>
              </form>
            </Card>
          ) : (
            <Card title="Decision"><Row k="Outcome" v={<Badge status={a.status} />} /><Row k="Decided by" v={a.decision_by ? label(a.decision_by) : '—'} /><Row k="Date" v={D(a.decided_at)} />{a.decision_note && <p className="mt-3 rounded-xl bg-slate-50 p-3 text-sm text-slate-600">{a.decision_note}</p>}</Card>
          )}
        </div>
      </div>
    </>
  );
}

async function decideApplicationApprove(fd: FormData) { 'use server'; fd.set('decision', 'approved'); return decideApplication(fd); }
async function decideApplicationDecline(fd: FormData) { 'use server'; fd.set('decision', 'declined'); return decideApplication(fd); }
